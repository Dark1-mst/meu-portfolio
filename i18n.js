const HTML_LANG_MAP = { pt: 'pt-BR', en: 'en', es: 'es', ru: 'ru' };

window.applyLanguage = function applyLanguage(lang) {
  const dict = window.I18N[lang] || window.I18N.pt;

  document.documentElement.lang = HTML_LANG_MAP[lang] || 'en';

  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (dict[key]) el.textContent = dict[key];
  });

  document.querySelectorAll('[data-i18n-html]').forEach((el) => {
    const key = el.getAttribute('data-i18n-html');
    if (dict[key]) el.innerHTML = dict[key];
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (dict[key]) el.setAttribute('placeholder', dict[key]);
  });

  const titleEl = document.getElementById('page-title');
  if (titleEl && dict['meta.title']) titleEl.textContent = dict['meta.title'];
  const descEl = document.getElementById('meta-description');
  if (descEl && dict['meta.description']) descEl.setAttribute('content', dict['meta.description']);

  const langSelect = document.getElementById('lang-select');
  if (langSelect && langSelect.value !== lang) langSelect.value = lang;

  localStorage.setItem('lang', lang);
  window.currentLang = lang;

  document.dispatchEvent(new CustomEvent('languagechange', { detail: { lang } }));
};
